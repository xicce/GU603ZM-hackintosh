#!/bin/bash

# ALC285 live topology probe. Run after booting the EFI with alc-verbs=1.
ALC="/Users/xicce/Documents/参考资料/ALC声卡定制-工具包/05-AudioSwitch-App/AudioSwitch.app/Contents/Resources/alc-verb"

if [ ! -x "$ALC" ]; then
  echo "找不到 alc-verb: $ALC"
  exit 1
fi

v() { "$ALC" "$1" "$2" "$3" 2>/dev/null | tail -1; }

echo "===== Codec identity ====="
printf 'node 0x00 -> %s\n' "$(v 0x00 0xF00 0x00)"

echo
echo "===== Widget caps / connection lengths ====="
for n in 0x02 0x03 0x04 0x05 0x06 0x07 0x08 0x09 0x0a 0x0b 0x0c 0x0d 0x0e 0x0f \
         0x10 0x11 0x12 0x13 0x14 0x15 0x16 0x17 0x18 0x19 0x1a 0x1b 0x1c 0x1d 0x1e 0x1f \
         0x20 0x21 0x22 0x23 0x24 0x25 0x26; do
  printf '%s wcaps=%s connlen=%s\n' "$n" "$(v "$n" 0xF00 0x09)" "$(v "$n" 0xF00 0x0E)"
done

echo
echo "===== Connection lists ====="
for n in 0x07 0x08 0x09 0x0a 0x0b 0x0c 0x0d 0x0e 0x0f 0x12 0x13 0x14 0x16 0x17 0x1b 0x21 0x22 0x23 0x24 0x25 0x26; do
  printf '%s:' "$n"
  for p in 0 4 8 12; do printf ' [%s]=%s' "$p" "$(v "$n" 0xF02 "$p")"; done
  echo
done

echo
echo "===== Pin caps / controls / sense / EAPD ====="
for n in 0x11 0x12 0x14 0x15 0x16 0x17 0x18 0x19 0x1a 0x1b 0x1c 0x1d 0x1e 0x1f 0x20 0x21; do
  printf '%s caps=%s ctl=%s sense=%s eapd=%s\n' "$n" "$(v "$n" 0xF00 0x0C)" "$(v "$n" 0xF07 0x00)" "$(v "$n" 0xF09 0x00)" "$(v "$n" 0xF0C 0x00)"
done

echo
echo "===== Pin config ====="
for n in 0x11 0x12 0x14 0x15 0x16 0x17 0x18 0x19 0x1a 0x1b 0x1c 0x1d 0x1e 0x1f 0x20 0x21; do
  echo "$n -> $(v "$n" 0xF1C 0x00)"
done

echo
echo "===== Runtime audio state (run while audio is playing) ====="
for n in 0x02 0x03 0x06 0x07 0x08 0x09 0x14 0x17 0x19 0x1b 0x21 0x24; do
  printf '%s stream=%s format=%s pinctl=%s connsel=%s\n' \
    "$n" "$(v "$n" 0xF06 0x00)" "$(v "$n" 0xF0A 0x00)" \
    "$(v "$n" 0xF07 0x00)" "$(v "$n" 0xF01 0x00)"
done
